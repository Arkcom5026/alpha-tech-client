const getRepairHelpSection = (sectionId) =>
  repairHelpSections.find((section) => section.id === sectionId) || repairHelpSections[0];

const inferRepairHelpSection = (pathname = '') => {
  if (pathname.includes('repair-intake')) return 'intake';
  if (pathname.includes('warranty-claims')) return 'claim';
  if (/\/repairs\/[^/]+/.test(pathname)) return 'queue';
  if (pathname.includes('/repairs')) return 'control-center';
  return 'overview';
};

export { repairHelpSections, getRepairHelpSection, inferRepairHelpSection };
